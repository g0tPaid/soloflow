export function getGuide(slug: string) {
  return guides.find((guide) => guide.slug === slug);
}

export function getGuidesForProduct(productSlug: string) {
  return guides.filter((guide) => guide.relatedProductSlugs.includes(productSlug));
}

export function searchGuides(query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return [];

  return guides.filter((guide) =>
    [
      guide.title,
      guide.excerpt,
      guide.intro,
      guide.seoTitle,
      guide.seoDescription,
      ...guide.relatedProductSlugs,
      ...guide.sections.flatMap((section) => [section.h2, ...section.paragraphs]),
      ...guide.faqs.flatMap((faq) => [faq.q, faq.a]),
    ]
      .join(' ')
      .toLowerCase()
      .includes(q),
  );
}
